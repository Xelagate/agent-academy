#!/usr/bin/env python3
"""Voice the helper's Bridge lines with Kokoro, locally (free, no key).

Usage: demo/voice/.venv/bin/python demo/voice/generate.py --voice af_heart [--sample]
Reads CONTENT.bridge.say from demo/content.en.js, writes demo/assets/voice/<id>.mp3 for lines that
are new or changed (hashes.json), deletes files for lines that are gone, and rewrites manifest.js.
--sample renders only `hello` into demo/voice/samples/<voice>.mp3 for listening.
"""
import argparse, hashlib, json, subprocess, tempfile, wave
from pathlib import Path

import numpy as np
from kokoro_onnx import Kokoro

HERE = Path(__file__).resolve().parent
DEMO = HERE.parent
OUT = DEMO / 'assets' / 'voice'
HASHES = HERE / 'hashes.json'

# Per-creature lines become "<id>.<creature>", matching bridgeLine() in levels/bridge.js.
FLATTEN = ("const C=require('./content.en.js');const o={};"
           "for(const[k,v]of Object.entries(C.bridge.say)){if(typeof v==='string')o[k]=v;"
           "else for(const[c,t]of Object.entries(v))o[k+'.'+c]=t;}console.log(JSON.stringify(o))")


def lines():
    return json.loads(subprocess.check_output(['node', '-e', FLATTEN], cwd=DEMO))


def render(kokoro, text, voice, mp3):
    samples, rate = kokoro.create(text.replace('’', "'"), voice=voice, speed=0.95, lang='en-us')
    pcm = (np.clip(samples, -1, 1) * 32767).astype(np.int16)
    with tempfile.NamedTemporaryFile(suffix='.wav') as tmp:
        with wave.open(tmp.name, 'wb') as w:
            w.setnchannels(1); w.setsampwidth(2); w.setframerate(rate); w.writeframes(pcm.tobytes())
        subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', tmp.name, '-ac', '1', '-b:a', '48k', str(mp3)], check=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--voice', required=True)
    ap.add_argument('--sample', action='store_true')
    args = ap.parse_args()
    kokoro = Kokoro(str(HERE / 'models' / 'kokoro-v1.0.onnx'), str(HERE / 'models' / 'voices-v1.0.bin'))
    all_lines = lines()

    if args.sample:
        (HERE / 'samples').mkdir(exist_ok=True)
        render(kokoro, all_lines['hello'], args.voice, HERE / 'samples' / f'{args.voice}.mp3')
        return

    OUT.mkdir(parents=True, exist_ok=True)
    old = json.loads(HASHES.read_text()) if HASHES.exists() else {}
    new = {}
    for lid, text in all_lines.items():
        new[lid] = hashlib.sha256(f'{args.voice}|{text}'.encode()).hexdigest()[:16]
        mp3 = OUT / f'{lid}.mp3'
        if old.get(lid) != new[lid] or not mp3.exists():
            render(kokoro, text, args.voice, mp3)
            print('voiced', lid)
    for mp3 in OUT.glob('*.mp3'):
        if mp3.stem not in all_lines:
            mp3.unlink()
            print('removed', mp3.name)
    HASHES.write_text(json.dumps(new, indent=1, sort_keys=True) + '\n')
    entries = ''.join(f'  {json.dumps(k)}: "assets/voice/{k}.mp3",\n' for k in sorted(all_lines))
    (HERE / 'manifest.js').write_text(
        '// demo/voice/manifest.js — generated by demo/voice/generate.py, do not edit.\n'
        f'const VOICE = {{\n{entries}}};\n'
        "if (typeof module !== 'undefined') module.exports = VOICE;\n")


if __name__ == '__main__':
    main()
